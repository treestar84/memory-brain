#!/usr/bin/env bun
/**
 * cfgm-compose — R-COMPOSE inference CLI
 *
 * Computes COMPOSES triples (transitive closure of DELEGATES_TO) and
 * detects cycles in the cross-skill delegation graph.
 *
 * Usage:
 *   bun run bin/cfgm-compose.ts [--json] [--no-report] [--output <path>]
 *
 * Reads from: memory/indexes/search.sqlite (build with cfgm-rebuild-index first)
 * Writes to:  memory/reports/skill-cycles.md (if cycles found, unless --no-report)
 */
import { Database } from "bun:sqlite";
import { existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { resolveStorageRoot, resolveProjectRoot } from "../src/hooks/bootstrap";
import { KGComposer } from "../src/core/search/KGComposer";
import { KGGraph } from "../src/core/search/KGGraph";

const args = process.argv.slice(2);
const jsonMode = args.includes("--json");
const noReport = args.includes("--no-report");
const outputIdx = args.indexOf("--output");
const outputPath = outputIdx !== -1 ? args[outputIdx + 1] : null;

const storageRoot = resolveStorageRoot();
const projectRoot = resolveProjectRoot();
const indexPath = join(storageRoot, "indexes", "search.sqlite");

if (!existsSync(indexPath)) {
  const msg = "search.sqlite not found — run cfgm-rebuild-index first";
  if (jsonMode) {
    console.log(JSON.stringify({ error: msg }));
  } else {
    console.error(`Error: ${msg}`);
  }
  process.exit(1);
}

const db = new Database(indexPath, { readonly: true });

let result;
let danglingCount = 0;
try {
  const composer = new KGComposer(db);
  result = composer.compose();
  danglingCount = new KGGraph(db).stats().danglingCount;
} finally {
  db.close();
}

if (jsonMode) {
  console.log(JSON.stringify(result, null, 2));
  process.exit(0);
}

// Human-readable output
console.log("\n=== R-COMPOSE Inference Report ===\n");
console.log(`Direct DELEGATES_TO edges : ${result.directEdgeCount}`);
console.log(`COMPOSES triples (derived): ${result.triples.length}`);
console.log(`Cycles detected           : ${result.cycles.length}`);

if (result.triples.length > 0) {
  console.log("\n── COMPOSES triples ──");

  // Group by fromSkill
  const byFrom = new Map<string, typeof result.triples>();
  for (const t of result.triples) {
    if (!byFrom.has(t.fromSkill)) byFrom.set(t.fromSkill, []);
    byFrom.get(t.fromSkill)!.push(t);
  }

  for (const [from, triples] of byFrom) {
    console.log(`\n  ${from}`);
    for (const t of triples) {
      const depthLabel = t.depth === 1 ? "direct" : `depth ${t.depth}`;
      console.log(`    → ${t.toSkill}  (${depthLabel})  ${t.path}`);
    }
  }
} else if (danglingCount > 0) {
  console.log(
    `\n  (0 resolved DELEGATES_TO edges — but ${danglingCount} dangling edge(s) exist, pointing to a skill outside the` +
      ` normalized set. Run \`cfgm graph-query dangling\` to see them; rebuilding the index won't resolve them.)`,
  );
} else {
  console.log("\n  (no DELEGATES_TO edges found in this skill set)");
}

if (result.cycles.length > 0) {
  console.log("\n── ⚠  Cycles detected ──");
  for (const c of result.cycles) {
    console.log(`  ${c.path}`);
  }
}

// Write cycle report
if (!noReport && result.cycles.length > 0) {
  const reportDir = join(projectRoot, "memory", "reports");
  if (!existsSync(reportDir)) mkdirSync(reportDir, { recursive: true });

  const reportFile = outputPath ?? join(reportDir, "skill-cycles.md");
  const now = new Date().toISOString();

  const lines = [
    `# Skill Delegation Cycles`,
    ``,
    `> Generated by \`cfgm-compose\` at ${now}`,
    `> Source: kg_edges (DELEGATES_TO, resolved=1)`,
    ``,
    `## Summary`,
    ``,
    `| Metric | Value |`,
    `|--------|-------|`,
    `| Direct DELEGATES_TO edges | ${result.directEdgeCount} |`,
    `| COMPOSES triples | ${result.triples.length} |`,
    `| Cycles | ${result.cycles.length} |`,
    ``,
    `## Detected Cycles`,
    ``,
    ...result.cycles.flatMap((c, i) => [
      `### Cycle ${i + 1}`,
      ``,
      `\`\`\``,
      c.path,
      `\`\`\``,
      ``,
      `Skills involved: ${c.skills.slice(0, -1).join(", ")}`,
      ``,
    ]),
    `## Action`,
    ``,
    `Review \`ProtocolNode.delegateTo\` in the listed skills and break the cycle`,
    `by removing or redirecting at least one delegation edge.`,
    ``,
  ];

  await Bun.write(reportFile, lines.join("\n"));
  console.log(`\n✓ Cycle report written → ${reportFile}`);
} else if (!noReport && result.cycles.length === 0) {
  // Clean up stale report if it exists
  const reportFile = outputPath ?? join(projectRoot, "memory", "reports", "skill-cycles.md");
  if (existsSync(reportFile)) {
    await Bun.write(
      reportFile,
      `# Skill Delegation Cycles\n\n> No cycles detected as of ${new Date().toISOString()}.\n`,
    );
    console.log(`\n✓ No cycles — report cleared → ${reportFile}`);
  }
}

console.log();
